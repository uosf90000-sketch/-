const SAMPLES = 96;
const NEIGHBOURHOOD = 2;
const BAND_FRACTION = 0.15;
const MAX_SWEEP_DEG = 115;
/** دائرةٌ ممتلئةٌ ليست بابًا: طاولةٌ مستديرةٌ أو حوض */
const MAX_CIRCLE_COVERAGE = 0.45;
/** تغطيةٌ عند هذا الحدّ فأكثرَ تعني دائرةً مغلقةً لا قوسًا */
const CLOSED_CIRCLE_COVERAGE = 0.85;
/** أقصى تشتّتٍ نسبيٍّ لبُعد الحبر عن المفصلة — فوقه ليس قوسًا حول هذه المفصلة */
const MAX_RADIAL_SPREAD = 0.06;
/** كم من مساحةِ الكنسِ يُسمَح أن يكون محبَّرًا قبل أن يسقط الادّعاء */
const MAX_SWEPT_INK = 0.25;
/** كم من خطٍّ مارٍّ بالمفصلة يجب أن يكون محبَّرًا ليُعَدّ جدارًا */
const STRAIGHT_WALL_FILL = 0.85;
/** ما شذَّ عن وسيطِ نصفِ القطر بأكثرَ من هذا ليس من أبواب هذا المبنى */
const RADIUS_TOLERANCE = 0.2;

function inkNear(mask: RasterMask, x: number, y: number, radius: number): boolean {
  const cx = Math.round(x);
  const cy = Math.round(y);
  for (let dy = -radius; dy <= radius; dy += 1) {
    for (let dx = -radius; dx <= radius; dx += 1) {
      const px = cx + dx;
      const py = cy + dy;
      if (px < 0 || py < 0 || px >= mask.width || py >= mask.height) continue;
      if (mask.dark[py * mask.width + px]) return true;
    }
  }
  return false;
}

/**
 * أطولُ امتدادٍ دائريٍّ يسمح بفجواتٍ قصيرة.
 *
 * يُمسح مرّتين حول الدائرة لأن الامتدادَ قد يعبر الصفر.
 */
function longestRun(on: readonly boolean[], maxGap: number): { length: number; start: number } {
  let best = 0;
  let bestStart = 0;
  let current = 0;
  let start = 0;
  let gap = 0;
  for (let i = 0; i < on.length * 2; i += 1) {
    if (on[i % on.length]) {
      if (current === 0) start = i - gap;
      current += gap + 1;
      gap = 0;
      if (current > best) {
        best = current;
        bestStart = start;
      }
    } else if (current > 0 && gap < maxGap) {
      gap += 1;
    } else {
      current = 0;
      gap = 0;
    }
  }
  return { length: Math.min(best, on.length), start: bestStart };
}

/**
 * هل المساحةُ التي يكنسها البابُ خالية؟
 *
 * البابُ يدور على أرضٍ فارغة — تلك وظيفةُ القوس أصلًا: أن يقول «لا تضع
 * هنا شيئًا». فما بين المفصلةِ والقوسِ داخل زاويةِ الدوران يجب أن يخلوَ
 * من الحبر.
 *
 * وهذا الشاهدُ هو ما يفرز **الدائرةَ الكاملة** من القوس. فدائرةٌ مرسومةٌ
 * كاملةً — طاولةٌ مستديرةٌ أو حوض — تُقرأ قوسًا إذا نُظر إليها من مركزٍ
 * مُزاح: يظهر جزءٌ منها على دائرةِ الفحص فيبدو امتدادًا رفيعًا. لكن حبرَها
 * حينئذٍ يقع **داخل** القطاع، فيسقط الادّعاء.
 */
function sweptAreaIsClear(
  mask: RasterMask,
  cx: number,
  cy: number,
  radiusPx: number,
  startIndex: number,
  runLength: number,
  maxSweptInk: number
): boolean {
  let probes = 0;
  let inked = 0;
  for (let k = 1; k < runLength - 1; k += 2) {
    const angle = (2 * Math.PI * ((startIndex + k) % SAMPLES)) / SAMPLES;
    const ca = Math.cos(angle);
    const sa = Math.sin(angle);
    for (const fraction of [0.45, 0.7]) {
      probes += 1;
      if (inkNear(mask, cx + ca * radiusPx * fraction, cy + sa * radiusPx * fraction, 1)) inked += 1;
    }
  }
  if (probes === 0) return false;
  return inked / probes <= maxSweptInk;
}

/**
 * هل يقع الحبرُ على **نفس** البُعد من المفصلة طولَ الامتداد؟
 *
 * هذا هو الفرقُ بين قوسٍ حقيقيٍّ ودائرةٍ كاملةٍ يُنظَر إليها من مركزٍ مُزاح.
 * فدائرةٌ نصفُ قطرها ‎60‎ حول نقطةٍ تبعد ‎11‎ بكسلًا تلامس دائرةَ فحصٍ نصفُ
 * قطرها ‎70‎ على امتدادٍ طويل، فتُقرأ قوسًا بعرضِ ‎109°‎ وهي دائرةُ طاولة.
 * لكنّ بُعدَ حبرِها عن المفصلة يتراوح بين ‎49‎ و‎71‎، بينما القوسُ الحقيقيُّ
 * يبقى على بُعدٍ واحدٍ لأنه مرسومٌ حول تلك المفصلة بعينها.
 *
 * فيُقاس البُعدُ الفعليُّ لأوّل حبرٍ على كلِّ شعاع، ويُطلَب أن يكون تشتّتُه
 * ضئيلًا. والقياسُ من الرسم لا من الافتراض.
 *
 * وثمنُه معلومٌ ومقيس: بابُ المدخل السفليِّ في مخطط العميل يُكتَب نصُّ
 * المساحة داخل قوسه، فيلقاه الشعاعُ قبل القوس ويتشتّت القياسُ فيسقط. جُرِّب
 * أخذُ الحبرِ الأقربِ إلى نصف القطر بدل أوّلِه، فلم يستردَّ ذلك البابَ
 * **وأسقط** حاجزَ الدائرةِ المغلقة — فبقي الأوّل.
 */
function radiallyTight(
  mask: RasterMask,
  cx: number,
  cy: number,
  radiusPx: number,
  startIndex: number,
  runLength: number
): boolean {
  const distances: number[] = [];
  for (let k = 0; k < runLength; k += 2) {
    const angle = (2 * Math.PI * ((startIndex + k) % SAMPLES)) / SAMPLES;
    const ca = Math.cos(angle);
    const sa = Math.sin(angle);
    let found = -1;
    for (let t = radiusPx * 0.6; t <= radiusPx * 1.4; t += 1) {
      if (inkNear(mask, cx + ca * t, cy + sa * t, 0)) {
        found = t;
        break;
      }
    }
    if (found > 0) distances.push(found);
  }
  if (distances.length < 4) return false;
  const mean = distances.reduce((sum, value) => sum + value, 0) / distances.length;
  if (!(mean > 0)) return false;
  const variance = distances.reduce((sum, value) => sum + (value - mean) ** 2, 0) / distances.length;
  return Math.sqrt(variance) / mean <= MAX_RADIAL_SPREAD;
}

/**
 * هل يوجد قربَ هذا المرشَّح مركزٌ تُغلَق حوله الدائرةُ كاملة؟
 *
 * الدائرةُ الكاملةُ لا تُهزَم بقياسِ التغطيةِ من مركزِ المرشَّح وحدَه: دائرةٌ
 * نصفُ قطرها ‎60‎ يُنظَر إليها من نقطةٍ تبعد ‎8‎ بكسلاتٍ تُقرأ قوسًا نصفُ قطره
 * ‎65‎ بعرضِ ‎97°‎ — وبُعدُ حبرِها عن تلك النقطة متّسقٌ على ذلك الامتداد، فلا
 * يفضحه اتّساقُ نصف القطر أيضًا.
 *
 * والفرقُ الذي لا يُخطئ: الدائرةُ **تُغلَق**، والقوسُ ينتهي. فيُبحَث في
 * جوارٍ صغيرٍ عن مركزٍ ونصفِ قطرٍ تكتمل حولهما الدائرة. ووجودُ مثلِه يعني
 * أن ما رأيناه طاولةٌ مستديرةٌ أو حوضٌ أو عمود، لا بابًا.
 */
function closesIntoCircle(mask: RasterMask, cx: number, cy: number, radiusPx: number): boolean {
  for (let dy = -14; dy <= 14; dy += 2) {
    for (let dx = -14; dx <= 14; dx += 2) {
      for (let r = radiusPx - 18; r <= radiusPx + 18; r += 2) {
        if (r < 6) continue;
        let on = 0;
        for (let i = 0; i < SAMPLES; i += 2) {
          const angle = (2 * Math.PI * i) / SAMPLES;
          if (inkNear(mask, cx + dx + Math.cos(angle) * r, cy + dy + Math.sin(angle) * r, 1)) on += 1;
        }
        if (on / (SAMPLES / 2) >= CLOSED_CIRCLE_COVERAGE) return true;
      }
    }
  }
  return false;
}

/**
 * هل تقف المفصلةُ على **جدار**، لا على حرفٍ من نصّ؟
 *
 * «حبرٌ تحت المفصلة» شرطٌ ضعيف: النصُّ حبرٌ أيضًا. وقياسًا على مخططٍ ثانٍ
 * فيه عمودُ نصٍّ تسويقيّ، أعطى تخفيفُ زاويةِ القوس **مئاتِ** المرشّحين
 * مجتمعين في ذلك العمود وحدَه — الحروفُ منحنياتٌ رفيعةٌ قصيرة، وهي بالضبط
 * ما يبحث عنه الكاشف.
 *
 * والجدارُ يفترق عن الحرف بأنه **مستقيمٌ طويل**. ويُسأل عنه **شعاعًا** لا
 * خطًّا: المفصلةُ تقف عند قائمةِ الباب — أي عند **طرف** الجدار — فالجدارُ
 * يمتدّ من عندها في جهةٍ واحدةٍ لا في جهتين. وقياسُ الخطِّ الكاملِ أسقط
 * أبوابَ المخطط الأوّل السبعةَ جميعًا لهذا السبب.
 */
function hingeStandsOnWall(mask: RasterMask, cx: number, cy: number, radiusPx: number): boolean {
  const reach = Math.max(8, Math.round(radiusPx * 0.9));
  const steps = Math.max(6, Math.round(reach / 2));
  for (let d = 0; d < 24; d += 1) {
    const angle = (2 * Math.PI * d) / 24;
    const ux = Math.cos(angle);
    const uy = Math.sin(angle);
    let hits = 0;
    let probes = 0;
    for (let k = 1; k <= steps; k += 1) {
      const t = (k / steps) * reach;
      probes += 1;
      if (inkNear(mask, cx + ux * t, cy + uy * t, 1)) hits += 1;
    }
    if (hits / probes >= STRAIGHT_WALL_FILL) return true;
  }
  return false;
}

/** قياسُ قوسٍ مفترَضٍ حول مركزٍ ونصفِ قطر */
function measureArc(
  mask: RasterMask,
  cx: number,
  cy: number,
  radiusPx: number,
  maxGap: number,
  minSweepDeg: number,
  maxSweptInk: number
): { sweepDeg: number } | null {
  const band = Math.max(6, Math.round(radiusPx * BAND_FRACTION));
  const thin: boolean[] = new Array(SAMPLES);
  let onCircle = 0;

  for (let i = 0; i < SAMPLES; i += 1) {
    const angle = (2 * Math.PI * i) / SAMPLES;
    const ca = Math.cos(angle);
    const sa = Math.sin(angle);
    const onArc = inkNear(mask, cx + ca * radiusPx, cy + sa * radiusPx, NEIGHBOURHOOD);
    if (onArc) onCircle += 1;
    // رفيعٌ يعني: حبرٌ على الدائرة وفراغٌ على جانبيها
    thin[i] =
      onArc &&
      !inkNear(mask, cx + ca * (radiusPx - band), cy + sa * (radiusPx - band), NEIGHBOURHOOD) &&
      !inkNear(mask, cx + ca * (radiusPx + band), cy + sa * (radiusPx + band), NEIGHBOURHOOD);
  }

  if (onCircle / SAMPLES > MAX_CIRCLE_COVERAGE) return null;
  const run = longestRun(thin, maxGap);
  const sweepDeg = (run.length / SAMPLES) * 360;
  if (sweepDeg < minSweepDeg || sweepDeg > MAX_SWEEP_DEG) return null;
  if (!sweptAreaIsClear(mask, cx, cy, radiusPx, run.start, run.length, maxSweptInk)) return null;
  if (!radiallyTight(mask, cx, cy, radiusPx, run.start, run.length)) return null;
  if (closesIntoCircle(mask, cx, cy, radiusPx)) return null;
  return { sweepDeg };
}

/**
 * البحثُ عن أقواس الأبواب في قناع المخطط.
 *
 * لا يُرجِع فتحاتٍ ولا يُسنِدها إلى جدار — يُرجِع **مواضعَ أقواسٍ مقيسة**.
 * وتحويلُها إلى فتحةٍ قرارٌ آخرُ في طبقةٍ أخرى، بعد إسنادها إلى جدارٍ من
 * المزوِّد.
 */
export function findDoorArcs(mask: RasterMask, options: DoorArcOptions = {}): DoorArcCandidate[] {
  const minRadius = options.minRadiusPx ?? Math.max(12, Math.round(mask.width * 0.03));
  const maxRadius = options.maxRadiusPx ?? Math.max(minRadius + 10, Math.round(mask.width * 0.07));
  const radiusStep = options.radiusStepPx ?? 5;
  const scanStep = options.scanStepPx ?? 3;
  const maxGap = options.maxGapSamples ?? 2;
  const minSweepDeg = options.minSweepDeg ?? 85;
  const minVotes = options.minVotes ?? 3;
  const maxSweptInk = options.maxSweptInk ?? MAX_SWEPT_INK;

  if (mask.width <= 0 || mask.height <= 0 || mask.dark.length !== mask.width * mask.height) return [];

  const raw: DoorArcCandidate[] = [];
  for (let cy = 0; cy < mask.height; cy += scanStep) {
    for (let cx = 0; cx < mask.width; cx += scanStep) {
      // المفصلةُ على الجدار، والجدارُ حبر
      if (!inkNear(mask, cx, cy, NEIGHBOURHOOD)) continue;
      if (!hingeStandsOnWall(mask, cx, cy, minRadius)) continue;
      for (let radiusPx = minRadius; radiusPx <= maxRadius; radiusPx += radiusStep) {
        const measured = measureArc(mask, cx, cy, radiusPx, maxGap, minSweepDeg, maxSweptInk);
        if (measured) raw.push({ hinge: { x: cx, y: cy }, radiusPx, sweepDeg: measured.sweepDeg, votes: 1 });
      }
    }
  }

  // عنقدةٌ بالموضع: نفسُ القوس يُرى من مراكزَ متجاورةٍ ونصفِ أقطارٍ متقاربة،
  // وكثرةُ الشهود دليلُ قوّةٍ لا تكرارٌ يُطرَح
  raw.sort((a, b) => b.sweepDeg - a.sweepDeg);
  const clustered: DoorArcCandidate[] = [];
  for (const candidate of raw) {
    const near = clustered.find(
      (existing) =>
        Math.hypot(existing.hinge.x - candidate.hinge.x, existing.hinge.y - candidate.hinge.y) <
        candidate.radiusPx * 0.5
    );
    if (near) {
      near.votes += 1;
      continue;
    }
    clustered.push({ ...candidate });
  }

  const strong = clustered.filter((candidate) => candidate.votes >= minVotes);
  if (strong.length === 0) return [];

  // أبوابُ مبنًى واحدٍ عرضُها واحدٌ تقريبًا — وما شذَّ ليس منها
  const radii = strong.map((candidate) => candidate.radiusPx).sort((a, b) => a - b);
  const median = radii[Math.floor(radii.length / 2)];
  return strong
    .filter((candidate) => Math.abs(candidate.radiusPx - median) <= median * RADIUS_TOLERANCE)
    .sort((a, b) => b.votes - a.votes);
}

// ============================================================
// البحثُ على الجدار وحدَه — يدلُّ المزوِّدُ، ويقرأ الرسم
// ============================================================
// المسحُ الشاملُ للصفحة سقط لسببٍ واحدٍ مقيس: عمودُ نصٍّ تسويقيٍّ أعطى ‎315‎
// مرشّحًا، والحرفُ منحنٍ رفيعٌ قصيرٌ وهو عينُ ما يبحث عنه الكاشف. ولمقاومةِ
// ذلك رُفعت عتبةُ الزاوية إلى ‎85°‎، فأعمت الكاشفَ عن مخططٍ يرسم أبوابَه
// نصفَ مفتوحة.
//
// والمخرجُ ليس عتبةً أذكى، بل **نطاقَ بحثٍ أضيق**.
//
// وقياسًا على واجهة Tectly نفسِها: ‎8‎ غرفٍ و‎3‎ أبواب، ثم ‎27‎ غرفةً و‎8‎
// أبواب. فغرفُه وجدرانُه جيّدة، وأبوابُه وحدَها ناقصة. فيُستعمَل ما يُتقنه
// دليلًا على ما لا يُتقنه: البابُ لا يكون إلا في جدار، والجدارُ يعرفه
// المزوِّد. فيُمسَح **شريطُ الجدار** لا الصفحة.
//
// وما يزول بذلك:
//
//   • النصُّ يخرج من النطاق أصلًا — فهو ليس على جدار.
//   • وتُرخى زاويةُ الفتح بأمان، لأن النطاقَ صار ضيّقًا: فيُقرأ البابُ
//     المرسومُ عند ‎45°‎ كما يُقرأ المرسومُ عند ‎90°‎.
//   • ويُعرَف موضعُ المفصلة: هي على وجهِ الجدار، لا في أيِّ مكان.
//
// ولا اختراعَ في ذلك: الغرفُ والجدرانُ من المزوِّد، والقوسُ من الرسم،
// وبيتي يربط بينهما فحسب.

/** شريطُ جدارٍ يُبحَث فيه عن قوس */
export interface WallBand {
  id: string;
  from: { x: number; y: number };
  to: { x: number; y: number };
  /** سماكةُ الجدار بالبكسل — المفصلةُ على أحد وجهيه */
  thicknessPx: number;
}

export interface WallArcOptions extends DoorArcOptions {
  /** كم بكسلًا بين مرشّحَي مفصلةٍ على طول الجدار */
  alongStepPx?: number;
}

/** قوسٌ وُجد على جدارٍ بعينه */
export interface WallDoorArc extends DoorArcCandidate {
  wallId: string;
  /** موضعُ المفصلة على طول الجدار، نسبةً من ‎0‎ إلى ‎1‎ */
  position: number;
}

/**
 * البحثُ عن أقواسِ الأبواب على جدرانٍ بعينها.
 *
 * المرشّحون يُؤخذون من **وجهَي الجدار** على امتداده، لا من الصورة كلِّها.
 * ولذلك تسقط شروطٌ صارت بلا معنًى — «المفصلةُ تقف على جدار» مضمونٌ بالبناء —
 * ويُرخى ما كان مشدودًا لمقاومةِ ضجيجٍ لم يعد في النطاق.
 */
export function findDoorArcsOnWalls(
  mask: RasterMask,
  bands: readonly WallBand[],
  options: WallArcOptions = {}
): WallDoorArc[] {
  if (mask.width <= 0 || mask.height <= 0 || mask.dark.length !== mask.width * mask.height) return [];

  const minRadius = options.minRadiusPx ?? Math.max(12, Math.round(mask.width * 0.02));
  const maxRadius = options.maxRadiusPx ?? Math.max(minRadius + 10, Math.round(mask.width * 0.08));
  const radiusStep = options.radiusStepPx ?? 5;
  const alongStep = options.alongStepPx ?? 4;
  const maxGap = options.maxGapSamples ?? 2;
  // النطاقُ ضيّقٌ، فالزاويةُ تُرخى: بابٌ نصفُ مفتوحٍ بابٌ أيضًا
  const minSweepDeg = options.minSweepDeg ?? 40;
  const minVotes = options.minVotes ?? 2;
  const maxSweptInk = options.maxSweptInk ?? MAX_SWEPT_INK;

  const found: WallDoorArc[] = [];

  for (const band of bands) {
    const dx = band.to.x - band.from.x;
    const dy = band.to.y - band.from.y;
    const length = Math.hypot(dx, dy);
    if (!(length > 0)) continue;
    const ux = dx / length;
    const uy = dy / length;
    // عمودُ الجدار: المفصلةُ على أحد وجهيه لا على محوره
    const half = Math.max(1, band.thicknessPx / 2);
    const nx = -uy * half;
    const ny = ux * half;

    const raw: WallDoorArc[] = [];
    for (let t = 0; t <= length; t += alongStep) {
      const ax = band.from.x + ux * t;
      const ay = band.from.y + uy * t;
      for (const side of [1, -1]) {
        const cx = Math.round(ax + nx * side);
        const cy = Math.round(ay + ny * side);
        if (cx < 0 || cy < 0 || cx >= mask.width || cy >= mask.height) continue;
        if (!inkNear(mask, cx, cy, NEIGHBOURHOOD)) continue;
        for (let radiusPx = minRadius; radiusPx <= maxRadius; radiusPx += radiusStep) {
          const measured = measureArc(mask, cx, cy, radiusPx, maxGap, minSweepDeg, maxSweptInk);
          if (!measured) continue;
          raw.push({
            wallId: band.id,
            hinge: { x: cx, y: cy },
            radiusPx,
            sweepDeg: measured.sweepDeg,
            votes: 1,
            position: Math.max(0, Math.min(1, t / length)),
          });
        }
      }
    }

    // عنقدةٌ داخل الجدار الواحد: نفسُ البابِ يُرى من مفاصلَ متجاورة
    raw.sort((a, b) => b.sweepDeg - a.sweepDeg);
    const clustered: WallDoorArc[] = [];
    for (const candidate of raw) {
      const near = clustered.find(
        (existing) =>
          Math.hypot(existing.hinge.x - candidate.hinge.x, existing.hinge.y - candidate.hinge.y) <
          candidate.radiusPx * 0.6
      );
      if (near) {
        near.votes += 1;
        continue;
      }
      clustered.push({ ...candidate });
    }
    found.push(...clustered.filter((candidate) => candidate.votes >= minVotes));
  }

  if (found.length === 0) return [];

  // أبوابُ مبنًى واحدٍ عرضُها واحدٌ تقريبًا — والوسيطُ يُؤخذ عبر الجدران كلِّها
  const radii = found.map((candidate) => candidate.radiusPx).sort((a, b) => a - b);
  const median = radii[Math.floor(radii.length / 2)];
  return found
    .filter((candidate) => Math.abs(candidate.radiusPx - median) <= median * RADIUS_TOLERANCE)
    .sort((a, b) => b.votes - a.votes);
}
