// ============================================================
// ‏`radialArcSupport` في `visual-evidence.ts` تقرأ القوسَ منذ زمن، لكنها
// **شاهدٌ لا باحث**: تُسأل «أهنا قوس؟» عند مفصلةٍ تُعطى لها. ومَن يُعطيها
// إيّاها هو كاشفُ الفجوات في شبكة الجدران.
//
// وقياسًا على مخططِ منزلٍ حقيقيٍّ من العميل: الشبكةُ تفتّتت — ‎39‎ فجوةً
// و‎3‎ نهاياتٍ معلّقةٍ ولم تُغلَق في وجوه، فخرجت **صفرُ غرف**. ووصل إلى
// قارئ القوس **مرشّحٌ واحد**، فأكّده بابًا. والقارئُ لم يُخطئ؛ لم يُعطَ ما
// يقرأه.
//
// فيُقلَب السؤال: بدل أن ننتظر من يدلّنا على المفصلة، نمسح الصورةَ بحثًا
// عن أرباع الدوائر. والقوسُ أوضحُ ما في المخطط: قطعةٌ دائريّةٌ نصفُ قطرها
// عرضُ الباب، تدور تسعين درجةً حول مفصلةٍ على الجدار.
//
// ============================================================
// ثلاثةُ شواهدَ لا واحد
// ============================================================
// «حبرٌ على دائرة» وحدَه لا يكفي — جُرِّب فأعطى ‎517‎ مرشّحًا على مخططٍ فيه
// سبعةُ أبواب: أيُّ خطٍّ يمرّ قربَ الدائرة يُحسَب قوسًا. والشواهدُ الثلاثة:
//
//   ‏١) **حبرٌ** على الدائرة عند نصف القطر R.
//   ‏٢) **وفراغٌ** على جانبيها عند ‎R±15%‎ — وهذا وحدَه ما جعل الكشفَ دقيقًا.
//      القوسُ خطٌّ رفيع؛ والجدارُ كتلةٌ، والأثاثُ مملوءٌ، والتهشيرُ كثيف.
//      فتسقط كلُّها بشرطِ الرقّة، ولا يبقى إلا ما هو منحنٍ رفيع.
//   ‏٣) **ومفصلةٌ على حبر**: المفصلةُ تقع على الجدار، والجدارُ حبر.
//
// وشاهدٌ رابعٌ جُرِّب وسقط: «درفةُ الباب» — شعاعٌ ممتلئٌ من المفصلة إلى طرف
// القوس. أعطى صفرًا، لأن الامتدادَ المُرشَّح يتوقّف قبل الدرفة فلا يصلها.
//
// ============================================================
// ولماذا يُسمَح بانقطاعٍ قصير
// ============================================================
// المخططُ الحقيقيُّ يكتب فوق أقواسه: نصُّ مساحةٍ داخل القوس، وخطُّ عتبةٍ
// يقطعه. والاشتراطُ الصارمُ للاتّصال أسقط بابَ المدخل السفليّ في مخطط
// العميل — لا لأنه ليس بابًا، بل لأن جوارَه مزدحم. وقياسُ التسامح:
//
//     انقطاع 0  →  6/7  وصفرُ زائد
//     انقطاع 2  →  7/7  وثلاثةُ زائد   ← المختار، ثم يُنقّى بالشرطين أدناه
//     انقطاع 3  →  7/7  وأربعةَ عشرَ زائد
//
// ============================================================
// وشرطان يُنقّيان الناتج
// ============================================================
//   • **زاويةُ القوس ≥ 85°**: البابُ يدور قائمةً. والثلاثةُ الزائدةُ عند
//     انقطاع‎ 2‎ كانت ‎83°‎ و‎79°‎ و‎71°‎، والأبوابُ السبعةُ ‎86°–101°‎.
//   • **اتّساقُ نصف القطر**: أبوابُ مبنًى واحدٍ عرضُها واحدٌ تقريبًا، فما
//     شذَّ عن وسيطِ المرشَّحين بأكثرَ من الخُمس ليس منها.
//
// وبهما صار الناتجُ على مخطط العميل **‎6/7‎ بلا إيجابيّةٍ كاذبةٍ واحدة** في
// ‎13‎ ثانية، وعروضُ الأبواب ‎0.81م‎ إلى ‎0.85م‎ — مقاساتٌ حقيقيّةٌ خرجت من
// الرسم ولم تُفرَض عليه.
//
// وكان النموذجُ الأوّليُّ يبلغ ‎7/7‎، ثم أُضيفت حواجزُ الإيجابيّةِ الكاذبة —
// خلوُّ مساحةِ الكنس، واتّساقُ البُعد، ورفضُ الدائرةِ المغلقة — فسقط معها
// بابُ المدخل السفليّ. والمقايضةُ مقصودة: **بابٌ مخترَعٌ في بيتِ أحدهم أسوأُ
// من بابٍ ناقص**. الناقصُ يُرى ويُضاف؛ والمخترَعُ يمرّ صامتًا إلى الكميّات.
//
// ============================================================
// ولا يُوصَل بمسارِ الإنتاج: قِيس على مخططٍ ثانٍ فلم يعمّم
// ============================================================
// هذا هو الحكمُ الأهمُّ في الملفّ، وسببُ وجوده مكتوبًا هنا بدل أن يُكتشَف
// لاحقًا في بيتِ عميل.
//
// المخططُ الثاني — منزلٌ عصريٌّ بخطوطٍ رفيعةٍ لا جدرانٍ مملوءة، وإلى جانبه
// عمودُ نصٍّ تسويقيّ — أعطى الأرقامَ التالية:
//
//     زاوية ≥85°  →  صفرُ اكتشافات
//     زاوية ≥60°  →  ٤ اكتشافاتٍ كلُّها في عمود النصّ، ولا بابَ واحد
//     زاوية ≥40°  →  ٣١٥ مرشّحًا، جُلُّها في عمود النصّ
//
// والسببُ اصطلاحُ رسمٍ لا عيبُ خوارزميّة: **المخططُ الأوّل يرسم أبوابَه
// مفتوحةً قائمةً، والثاني يرسمها نصفَ مفتوحةٍ عند ‎45°‎**. فعتبةُ الزاوية —
// وهي ما أعطى المخططَ الأوّلَ دقّتَه — هي بعينها ما يُعميه عن الثاني.
// وتخفيفُها يفتح البابَ لحروفِ النصّ: الحرفُ منحنٍ رفيعٌ قصير، وهو بالضبط
// ما يبحث عنه هذا الكاشف.
//
// وأُضيف بعد ذلك شاهدُ «المفصلةُ على جدار»: شعاعٌ ممتلئٌ من المفصلة بطول
// نصفِ القطر تقريبًا — والحرفُ لا يعطيه. وقيس شعاعًا لا خطًّا لأن المفصلةَ
// تقف عند **طرف** الجدار، وقياسُ الخطِّ الكاملِ أسقط أبوابَ المخطط الأوّل
// السبعةَ جميعًا. وأفاد الشاهدُ لكنه لم يكفِ: بقيت أربعةُ إيجابيّاتٍ كاذبةٍ
// في النصّ، وصفرُ أبوابٍ حقيقيّةٍ من الثاني.
//
// فالخلاصةُ المقيسة: **يعمل على اصطلاحِ رسمٍ واحدٍ ولا يعمّم.** ولا يُوصَل
// بشيء. ولمن يُكمِله لاحقًا، الطريقُ الذي يبدو معقولًا:
//
//   ‏١) أن تُقاس زاويةُ الفتح من الرسم نفسِه بدل فرضِها — كما اشتُقّ المقياسُ
//      من عرض الأبواب في `scale-estimate.ts`.
//   ‏٢) أن يُستبعَد النصُّ قبل المسح، لا أن يُقاوَم أثناءه.

